//! **M6C** § Files: generator binary that walks the
//! `cf_equipment::m6c_entries_by_category()` registry and writes one
//! `content/equipment/<category>/<id>.ron` file per SKU. Re-run after
//! adding a SKU to the M6C registry.
//!
//! Usage: `cargo run --bin generate_m6c_rons -- [<content_root>]`
//!
//! Default `content_root` is `<workspace>/content/equipment` resolved
//! relative to the crate's `CARGO_MANIFEST_DIR`.

use std::path::PathBuf;

use cf_equipment::m6c_entries_by_category;

fn main() -> anyhow::Result<()> {
    let argv: Vec<String> = std::env::args().collect();
    let content_root = if argv.len() >= 2 {
        PathBuf::from(&argv[1])
    } else {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..").join("content/equipment")
    };
    println!("writing M6C RON files under {}", content_root.display());

    let pretty = ron::ser::PrettyConfig::new()
        .struct_names(false)
        .depth_limit(10)
        .indentor("  ".to_string());

    let mut total_written = 0usize;
    for (category, entries) in m6c_entries_by_category() {
        let dir = content_root.join(category);
        std::fs::create_dir_all(&dir)?;
        for entry in &entries {
            let path = dir.join(format!("{}.ron", entry.id));
            let body = ron::ser::to_string_pretty(entry, pretty.clone())?;
            let header = format!(
                "// **M6C** SKU `{}` in category `{}`. Generated by\n// `cargo run --bin generate_m6c_rons` from\n// `cf_equipment::m6c_entries_by_category()`. Re-generate after registry edits.\n\n",
                entry.id, category
            );
            std::fs::write(&path, format!("{header}{body}\n"))?;
            total_written += 1;
        }
        println!("  {category}: {} SKUs", entries.len());
    }
    println!("wrote {total_written} RON files");
    Ok(())
}
